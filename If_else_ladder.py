choice = int(input("Choose a vehicle type (1 for Car, 2 for Bike, 3 for SUV): "))
if choice == 1:
    print("You have chosen a Car.")
elif choice == 2:
    print("You have chosen a Bike.")
elif choice == 3:
    print("You have chosen an SUV.")
    
else:
    print("Invalid choice. Please select a valid vehicle type.")